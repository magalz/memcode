"""Small, local fixtures for the actual native document/media viewer checks."""
from pathlib import Path
from math import sin, pi
import struct
import sys
import wave
from reportlab.pdfgen import canvas
from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4

root = Path(sys.argv[1])
root.mkdir(parents=True, exist_ok=True)
target = root / "review-guide.pdf"
c = canvas.Canvas(str(target), pagesize=A4)
c.setTitle("MemCode - Review in context")
w, h = A4
for page in range(1, 3):
    c.setFillColor(HexColor("#f8faf6")); c.rect(0, 0, w, h, fill=1, stroke=0)
    c.setFillColor(HexColor("#102b20")); c.rect(0, h-215, w, 215, fill=1, stroke=0)
    c.setFillColor(HexColor("#70dfbd")); c.setFont("Helvetica", 9)
    c.drawString(48, h-51, "MEMCODE / REVIEW STUDIO")
    c.setFillColor(HexColor("#f6faf6")); c.setFont("Helvetica-Bold", 30)
    c.drawString(48, h-110, "Review in context." if page == 1 else "Make the next move.")
    c.setFont("Helvetica", 12); c.setFillColor(HexColor("#a9c3b2"))
    c.drawString(48, h-145, "A precise quote. A clear request. The same shared work.")
    c.setFillColor(HexColor("#263f30")); c.setFont("Helvetica-Bold", 16)
    c.drawString(48, h-267, "Keep the source attached" if page == 1 else "A comment becomes a follow-up")
    lines = ["Select this sentence to ask for clearer wording.", "Your selection keeps its page and source document.", "Comments stay in MemCode until you choose to send them."] if page == 1 else ["The worker receives your request and the exact quoted passage.", "Review changes before accepting the result.", "Local execution. Coordinated workers. Clear evidence."]
    c.setFont("Helvetica", 12)
    for index, text in enumerate(lines):
        c.drawString(48, h-305-index*29, text)
    c.setStrokeColor(HexColor("#d5e1d3")); c.line(48, 65, w-48, 65)
    c.setFillColor(HexColor("#839780")); c.setFont("Helvetica", 9)
    c.drawString(48, 45, "Local viewer test fixture - not generated by a worker")
    c.drawRightString(w-48, 45, str(page) + " / 2")
    c.showPage()
c.save()
with wave.open(str(root / "review-tone.wav"), "wb") as audio:
    audio.setnchannels(1); audio.setsampwidth(2); audio.setframerate(22050)
    audio.writeframes(b"".join(struct.pack("<h", int(3000*sin(2*pi*220*i/22050))) for i in range(33075)))
print(target)
